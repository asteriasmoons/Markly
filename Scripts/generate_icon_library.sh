#!/bin/bash
#
# generate_icon_library.sh
# Markly
#
# Regenerates Markly/Utilities/IconLibrary.swift from the folder structure of
# Markly/Assets.xcassets. Each group folder in the catalog (with "Provides
# Namespace" OFF) becomes one IconCategory; every *.imageset inside it becomes
# a MarklyIcon. Imagesets sitting at the catalog root land in an "Unsorted"
# category so new icons are never silently missing.
#
# Runs as a pre-"Compile Sources" build phase. It only rewrites the Swift file
# when the output actually changes, so unchanged builds cause no recompile and
# no source-control churn.
#
# Written for macOS /bin/bash (3.2) compatibility; LC_ALL=C keeps the output
# byte-identical on any machine.

set -euo pipefail
export LC_ALL=C

# $SRCROOT is provided by Xcode; fall back to repo root when run by hand.
SRCROOT="${SRCROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
CAT="${1:-$SRCROOT/Markly/Assets.xcassets}"
OUT="${2:-$SRCROOT/Markly/Utilities/IconLibrary.swift}"

if [ ! -d "$CAT" ]; then
  echo "error: asset catalog not found at $CAT" >&2
  exit 1
fi

# Preferred category order. "UI" is always forced last; unknown folders slot in
# just before it; "Unsorted" sits right before "UI".
ORDER=(
  "Bookmarks & Books" "Rooms" "Cleaning" "Kitchen" "Love & Calendar"
  "Charts & Social" "Tags & Shapes" "Office & Tech" "Wellness & Self-Care"
  "Stars & Awards" "Outdoors & Storage" "Money & Shopping" "Art & Writing"
  "Chat & Messages" "Language & Learning" "Keyboard & Input" "Editing & Layout"
  "Moon Phases" "Misc"
)

MAP="$(mktemp)"
TMPOUT="$(mktemp)"
trap 'rm -f "$MAP" "$TMPOUT" 2>/dev/null || true' EXIT

# Map every *.imageset -> "CATEGORY<TAB>ID"
while IFS= read -r iset; do
  parent="$(dirname "$iset")"
  base="$(basename "$iset")"
  id="${base%.imageset}"
  if [ "$parent" = "$CAT" ]; then
    cat_name="Unsorted"
  else
    cat_name="$(basename "$parent")"
  fi
  printf '%s\t%s\n' "$cat_name" "$id"
done < <(find "$CAT" -type d -name '*.imageset' | sort) > "$MAP"

# Distinct categories actually present
PRESENT=()
while IFS= read -r line; do PRESENT+=("$line"); done < <(cut -f1 "$MAP" | sort -u)

contains() { # contains <needle> <haystack items...>
  local needle="$1"; shift
  local x
  for x in "$@"; do [ "$x" = "$needle" ] && return 0; done
  return 1
}

# Final ordered list: known order (minus UI), then unknown folders (alpha),
# then Unsorted, then UI.
FINAL=()
for c in "${ORDER[@]}"; do
  [ "$c" = "UI" ] && continue
  if contains "$c" "${PRESENT[@]}"; then FINAL+=("$c"); fi
done
for c in "${PRESENT[@]}"; do
  case "$c" in "UI"|"Unsorted") continue ;; esac
  if ! contains "$c" "${ORDER[@]}"; then FINAL+=("$c"); fi
done
contains "Unsorted" "${PRESENT[@]}" && FINAL+=("Unsorted")
contains "UI" "${PRESENT[@]}" && FINAL+=("UI")

emit_category() {
  local name="$1"
  local ids=() id np maxlen=0 pad
  while IFS= read -r id; do ids+=("$id"); done \
    < <(awk -F'\t' -v c="$name" '$1==c{print $2}' "$MAP" | sort)
  for id in "${ids[@]}"; do
    np="MarklyIcon(\"$id\","
    [ ${#np} -gt $maxlen ] && maxlen=${#np}
  done
  printf '        IconCategory(name: "%s", icons: [\n' "$name"
  for id in "${ids[@]}"; do
    np="MarklyIcon(\"$id\","
    pad=$(( maxlen - ${#np} + 1 ))
    printf '            %s%*scustom: true),\n' "$np" "$pad" ""
  done
  printf '        ]),\n'
}

{
cat <<'HEADER'
//
//  IconLibrary.swift
//  Markly
//
//  AUTO-GENERATED by Scripts/generate_icon_library.sh — DO NOT EDIT BY HAND.
//  Categories are driven by the folder structure inside Assets.xcassets: each
//  group folder (with "Provides Namespace" OFF) becomes one IconCategory.
//  To re-categorize an icon, move its .imageset into another category folder in
//  the asset catalog; the next build regenerates this file.
//

import Foundation

// MARK: - Icon

struct MarklyIcon: Identifiable, Hashable {
    let id: String          // unique key, used to store in model
    let isCustom: Bool      // true = asset catalog

    init(_ id: String, custom: Bool = true) {
        self.id = id
        self.isCustom = custom
    }
}

// MARK: - Icon Category

struct IconCategory {
    let name: String
    let icons: [MarklyIcon]
}

// MARK: - Library

enum IconLibrary {
    static let categories: [IconCategory] = [
HEADER

for c in "${FINAL[@]}"; do
  printf '\n'
  emit_category "$c"
done

cat <<'FOOTER'
    ]

    /// All categories shown in the icon picker (excludes UI)
    static let pickerCategories: [IconCategory] = categories.filter {
        $0.name != "UI"
    }

    /// Flat list of all icons (includes UI)
    static let all: [MarklyIcon] = categories.flatMap { $0.icons }

    /// Flat list of picker icons only
    static let pickerIcons: [MarklyIcon] = pickerCategories.flatMap { $0.icons }
}
FOOTER
} > "$TMPOUT"

if [ -f "$OUT" ] && cmp -s "$TMPOUT" "$OUT"; then
  echo "IconLibrary.swift already up to date."
else
  cp "$TMPOUT" "$OUT"
  echo "IconLibrary.swift regenerated ($(grep -c 'MarklyIcon(' "$OUT" || true) icon entries, ${#FINAL[@]} categories)."
fi
